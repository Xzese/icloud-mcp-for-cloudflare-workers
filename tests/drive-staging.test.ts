const stream = (bytes: Uint8Array) => new Response(bytes.slice().buffer).body!;
const hash = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
test("multipart staging verifies exact parts, resumes durable state and reconciles lost completion responses", async t => {
  const db = new JobSQLiteD1(); t.after(() => db.sqlite.close());
  const owner = "synthetic-staging-owner", bucket = new DriveBucket();
  const env = { ...db.env(), REMINDERS_OWNER_ID: owner, ENCRYPTION_KEY_ID: "synthetic", ENCRYPTION_KEYS_JSON: JSON.stringify({ synthetic: b64(crypto.getRandomValues(new Uint8Array(32))) }) };
  const scope = { account: "synthetic-account", generation: 1, permissionRevision: 1, expiresAt: Date.now() + 86_400_000 };
  const repo = new DriveOperationRepository(env, owner);
  let revoked = false;
  const stage = () => new DriveStaging(bucket.binding(), repo, scope, async () => { if (revoked) throw new Error("permission revoked"); });
  const operationId = crypto.randomUUID(), part = new Uint8Array(DRIVE_UPLOAD_PART_BYTES).fill(65), last = new Uint8Array([66, 67, 68]);
  await repo.create(operationId, "upload", { operationId, size: part.length + last.length }, scope);
  await assert.rejects(stage().complete(operationId), { code: "CONFLICT" });
  await assert.rejects(stage().part(operationId, 1, hash(part), stream(part)), { code: "CONFLICT" });
  await assert.rejects(stage().discard(operationId), { code: "CONFLICT" });
  const prepared = await stage().prepare(operationId);
  assert.deepEqual(prepared.uploadedParts, []);
  assert.equal(prepared.partBytes, 8 * 1024 ** 2);
  assert.equal(JSON.stringify(prepared).includes("uploadId"), false);
  await assert.rejects(stage().complete(operationId), /every part/);
  await assert.rejects(stage().part(operationId, 0, hash(part), stream(part)), { code: "VALIDATION_ERROR" });
  await assert.rejects(stage().part(operationId, 1, hash(part), stream(last)), /exact byte length/);
  await assert.rejects(stage().part(operationId, 2, hash(last), stream(part)), { status: 413 });
  await assert.rejects(stage().part(operationId, 1, "0".repeat(64), stream(part)), /SHA-256/);
  assert.equal(bucket.partWrites, 0);
  await stage().part(operationId, 2, hash(last), stream(last));
  await stage().part(operationId, 1, hash(part), stream(part));
  assert.deepEqual((await stage().prepare(operationId)).uploadedParts, [1, 2]);
  await stage().part(operationId, 1, hash(part), stream(part));
  assert.equal(bucket.partWrites, 2, "a persisted part replay performs no R2 write");
  const changed = part.slice(); changed[0] = 9;
  await assert.rejects(stage().part(operationId, 1, hash(changed), stream(changed)), /different bytes/);
  revoked = true;
  await assert.rejects(stage().complete(operationId), /permission revoked/);
  revoked = false;
  // Simulate R2 complete succeeding before the D1 checkpoint was acknowledged.
  const data = await repo.data(await repo.get(operationId, scope));
  await bucket.resumeMultipartUpload(data.staging!.key, data.staging!.uploadId).complete(data.staging!.parts);
  const sealed = await stage().complete(operationId);
  assert.ok(sealed.objectEtag);
  assert.equal(bucket.objects.get(sealed.key)?.bytes.length, part.length + last.length);
  await assert.rejects(stage().part(operationId, 1, hash(part), stream(part)), /sealed/);
  assert.ok((await stage().discard(operationId)).cancelled);
  assert.ok((await stage().discard(operationId)).cancelled, "discard can be repeated safely");
  assert.equal(bucket.objects.size, 0);
  await assert.rejects(stage().complete(operationId), /discarded/);
  assert.equal(db.sqlite.prepare("SELECT lease_id FROM drive_operations WHERE operation_id = ?").get(operationId)?.lease_id, null);
  const otherScope = { ...scope, generation: 2 };
  await assert.rejects(new DriveStaging(bucket.binding(), repo, otherScope, async () => {}).prepare(operationId), { code: "FORBIDDEN" });
});

test("staging sweep deletes only expired complete objects; storage cleanup failures stay visible", async t => {
  const db = new JobSQLiteD1(); t.after(() => db.sqlite.close());
  const owner = "synthetic-cleanup-owner", bucket = new DriveBucket();
  const env = { ...db.env(), REMINDERS_OWNER_ID: owner, ENCRYPTION_KEY_ID: "synthetic", ENCRYPTION_KEYS_JSON: JSON.stringify({ synthetic: b64(crypto.getRandomValues(new Uint8Array(32))) }) };
  const scope = { account: "synthetic-account", generation: 1, permissionRevision: 1, expiresAt: Date.now() + 86_400_000 };
  const repo = new DriveOperationRepository(env, owner), id = crypto.randomUUID();
  await repo.create(id, "upload", { operationId: id, size: 3 }, scope);
  const expired = `drive-staging/v1/${Date.now() - 1}/${crypto.randomUUID()}`, active = `drive-staging/v1/${Date.now() + 60_000}/${crypto.randomUUID()}`;
  for (const key of [expired, active, "unrelated-private-object"]) bucket.objects.set(key, { bytes: new Uint8Array(), etag: crypto.randomUUID() });
  const staging = new DriveStaging(bucket.binding(), repo, scope, async () => {});
  await staging.prepare(id);
  assert.equal(bucket.objects.has(expired), false);
  assert.equal(bucket.objects.has(active), true); assert.equal(bucket.objects.has("unrelated-private-object"), true);
  const abort = t.mock.method(bucket, "resumeMultipartUpload", () => { throw new Error("synthetic storage outage"); });
  await assert.rejects(staging.discard(id), /storage outage/);
  abort.mock.restore();
  assert.ok((await staging.discard(id)).cancelled);
  const row = await repo.get(id, scope);
  assert.equal(row.phase, "prepared"); assert.equal((await repo.data(row)).staging?.cancelled, true);
});

test("multi-gigabyte sizes use safe integers and retain a small multipart manifest", () => {
  const metadata = { parentId: "FOLDER::com.apple.CloudDocs::root", name: "synthetic.bin", operationId: crypto.randomUUID(), sha256: "a".repeat(64) };
  for (const size of [2 ** 31 + 1, 2 ** 32 + 1, DRIVE_FILE_BYTES]) assert.ok(UploadDriveMetadata.safeParse({ ...metadata, size }).success);
  assert.equal(UploadDriveMetadata.safeParse({ ...metadata, size: DRIVE_FILE_BYTES + 1 }).success, false);
  assert.equal(Math.ceil(DRIVE_FILE_BYTES / DRIVE_UPLOAD_PART_BYTES), 1280);
});
